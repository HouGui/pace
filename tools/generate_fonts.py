"""Generate bounded LVGL Latin glyphs from the pinned LVGL Montserrat font.

Requires Pillow 13.0.0. Run after the firmware dependency download.
"""
from pathlib import Path
import subprocess
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'firmware/managed_components/lvgl__lvgl/scripts/built_in_font'
OUTPUT = ROOT / 'firmware/components/pace_ui/fonts'


def generate(size):
    font = ImageFont.truetype(str(SOURCE / 'Montserrat-Medium.ttf'), size)
    points = list(range(160, 256)) + [0x1e9e, 0x2013, 0x2014, 0x2026]
    if size == 32:
        points = list(range(32, 127)) + points
    bitmap, descriptors = [], ['{0}']
    for point in points:
        char = chr(point)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        width, height = right - left, bottom - top
        mask = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(mask).text((-left, -top), char, font=font, fill=255, anchor='ls')
        pixels = [round(mask.getpixel((x, y)) / 17) for y in range(height) for x in range(width)]
        index = len(bitmap)
        if len(pixels) % 2:
            pixels.append(0)
        bitmap += [(pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2)]
        descriptors.append(f'{{.bitmap_index={index}, .adv_w={round(font.getlength(char)*16)}, '
                           f'.box_w={width}, .box_h={height}, .ofs_x={left}, .ofs_y={-bottom}}}')
    lines = ['// Generated by tools/generate_fonts.py; font data: SIL OFL-1.1, see OFL.txt.',
             '#include "lvgl.h"', 'static const uint8_t pixels[] = {']
    lines += ['    ' + ','.join(str(v) for v in bitmap[i:i+24]) + ',' for i in range(0, len(bitmap), 24)]
    lines += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', ',\n'.join(descriptors), '};',
              'static const uint16_t points[] = {' + ','.join(str(v - points[0]) for v in points) + '};',
              'static const lv_font_fmt_txt_cmap_t cmaps[] = {{',
              f'.range_start={points[0]}, .range_length={points[-1]-points[0]+1}, .glyph_id_start=1,',
              f'.unicode_list=points, .list_length={len(points)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY',
              '}};', 'static const lv_font_fmt_txt_dsc_t data = {',
              '.glyph_bitmap=pixels, .glyph_dsc=glyphs, .cmaps=cmaps, .cmap_num=1, .bpp=4};',
              f'const lv_font_t pace_font_{size} = {{',
              '.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
              f'.line_height={19 if size==16 else 29 if size==24 else 38}, .base_line={4 if size==16 else 6 if size==24 else 8},',
              '.underline_position=-2, .underline_thickness=1, .dsc=&data,',
              f'.fallback=&lv_font_montserrat_{size},' if size != 32 else '', '};', '']
    (OUTPUT / f'pace_font_{size}.c').write_text('\n'.join(lines))


def main():
    OUTPUT.mkdir(exist_ok=True)
    for size in (16, 24, 32):
        generate(size)
    subprocess.run(['clang-format', '-i', *map(str, sorted(OUTPUT.glob('*.c')))], check=True)
    (OUTPUT / 'OFL.txt').write_bytes((SOURCE / 'font_license/Montserrat/OFL.txt').read_bytes())


if __name__ == '__main__':
    main()
